export type MechanicalFile = { path: string; sha256: string; rights: string;
  role: 'native' | 'recipe' | 'model' | 'supporting' | 'unsupported';
  format: 'freecad' | 'build123d' | 'cadquery' | 'step' | 'brep' | 'mesh' | 'other' };
export type MechanicalSourcePin = { local_id: string; source_revision_id: string; source_manifest_sha256: string; files: MechanicalFile[] };
export type BoardPin = { interpretation_id: string; interpretation_sha256: string; source_revision_id: string;
  source_manifest_sha256: string; option_id: string | null };
export type TargetPin = { local_id: string; role: 'board' | 'component' | 'hardware'; revision_id: string;
  snapshot_sha256: string; board: BoardPin | null; native_component_id: string | null; basis: string };
export type ModelPin = { local_id: string; representation_id: string; revision_id: string; snapshot_sha256: string;
  source_local_id: string; path: string; target_local_id: string; purpose: 'manufacturing' | 'clearance' | 'illustration';
  units: 'mm' | 'm' | 'in' | null; frame: string | null; accuracy: string | null; basis: string };
export type MechanicalSource = { schema_version?: '1'; item_role: 'enclosure' | 'part' | 'hardware';
  sources: MechanicalSourcePin[]; targets: TargetPin[]; models: ModelPin[]; limitations: string[] };
export type ModelChoice = { representation_id: string; label: string; revision_id: string; snapshot_sha256: string;
  source_revision_id: string; source_manifest_sha256: string; path: string; sha256: string; rights: string };
export type TargetChoice = { revision_id: string; snapshot_sha256: string; name: string; number: number; kind: string;
  board: (Omit<BoardPin, 'option_id'> & { options: { local_id: string; name: string }[] }) | null;
  components: { id: string; reference: string; value: string }[]; models: ModelChoice[]; models_truncated: boolean };
export type Finding = { code: string; status: 'valid' | 'invalid' | 'unknown' | 'not_evaluated'; message: string; local_id: string | null };
export type MechanicalRead = { definition_id: string; name: string; draft_id: string | null; state: string | null;
  revision_id: string | null; revision_number: number | null; snapshot_sha256: string | null;
  content: { mechanical_source: MechanicalSource }; evaluation: {
    sources: (MechanicalSourcePin & { name: string; number: number; role: string; derived_from: string | null; ancestry: string[] })[];
    targets: (TargetPin & { name: string; number: number; kind: string; component: { reference: string } | null;
      board_geometry: { outline: number[][][]; coverage: { outline: string }; coordinate_frame: string; units: string;
        extractor: { adapter: string; tool_version: string }; unsupported: string[] } | null })[];
    models: (ModelPin & { label: string; sha256: string; rights: string })[];
    findings: Finding[]; readiness: 'blocked' | 'declared_with_unknowns' | 'declared'; limitations: string[];
    native_execution: 'none'; geometry_validation: 'not_performed'; clearance: 'not_evaluated';
    fit: 'not_evaluated'; manufacturability: 'not_evaluated'; physical_qualification: false;
  } };
export type RecordPage = { records: { definition_id: string; name: string; drafts: { draft_id: string }[];
  revisions: { revision_id: string; number: number }[] }[]; next_after: string | null };
export type TargetPage = { targets: TargetChoice[]; next_after: string | null };
