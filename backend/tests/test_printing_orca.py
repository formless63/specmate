def fake_orca_root(tmp_path, presets):
    root = tmp_path / "orca"
    profiles = root / "resources" / "profiles"
    for role, kind in (("printer", "machine"), ("process", "process"), ("material", "filament")):
        item = presets[role]
        folder = profiles / item["vendor"] / kind
        folder.mkdir(parents=True, exist_ok=True)
        (profiles / (item["vendor"] + ".json")).write_text(
            json.dumps({"name": item["vendor"], "version": item["bundle_version"]})
        )
        (folder / "leaf.json").write_text(
            json.dumps({"name": item["name"], "inherits": "base " + kind, "instantiation": "true"})
        )
        (folder / "base.json").write_text(
            json.dumps({"name": "base " + kind, "parent_only_key": "from parent"})
        )
    app_run = root / "AppRun"
    app_run.write_text(f"#!{sys.executable}\n{FAKE_ORCA}")
    os.chmod(app_run, 0o700)
    release = tmp_path / "orcaslicer-release.txt"
    release.write_text(
        "\n".join(
            [
                "OrcaSlicer " + ORCA_TOOL["package_version"],
                ORCA_TOOL["package"],
                ORCA_TOOL["release_sha256"],
            ]
        )
        + "\n"
    )
    return root, release


def run_orca(tmp_path, spec, model):
    inputs, outputs = tmp_path / "in", tmp_path / "out"
    for d in (inputs, outputs):
        d.mkdir()
    (inputs / spec["part"]["path"]).write_bytes(model)
    root, release = fake_orca_root(tmp_path, spec["presets"])
    script = (
        orca_script.SCRIPT.replace('"/opt/orcaslicer"', repr(str(root)))
        .replace('"/opt/specmate/orcaslicer-release.txt"', repr(str(release)))
        .replace('"/inputs"', repr(str(inputs)))
        .replace('"/outputs"', repr(str(outputs)))
        .replace('"/tmp/specmate-orca"', repr(str(tmp_path / "work")))
    )
    done = subprocess.run(  # noqa: S603 - this interpreter and the trusted adapter text
        [sys.executable, "-I", "-c", script, canonical(spec).decode()],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    return done, outputs


def register_outputs(build_id, files, media, report_path, rights=RIGHTS):
    """Register immutable evidence as the runner would; this is not native proof."""
    stage = BuildStage.objects.get(build_id=build_id)
    for path, data in files.items():
        staged = blobstore.stage(io.BytesIO(data), 2 * 1024**2)
        blobstore.promote(staged)
        StageOutput.objects.create(
            stage=stage,
            path=path,
            sha256=digest(data),
            size=len(data),
            media_type=media[path],
            rights=rights,
            source_revision_id=stage.build.source_revision_id,
        )
    stage.state = "succeeded"
    stage.receipt = {
        "outcome": "succeeded",
        "exit_code": 0,
        "outputs": [{"path": p, "sha256": digest(d)} for p, d in sorted(files.items())],
    }
    stage.save()


def test_orca_adapter_flattens_presets_and_its_evidence_is_accepted(
    users, orca_frozen, orca_approved, tmp_path
):
    spec = json.loads(orca_approved["argv"][-1])
    done, outputs = run_orca(tmp_path, spec, MODEL)
    assert done.returncode == 0, done.stderr
    report = json.loads((outputs / "slice.json").read_text())
    assert report["estimates"]["print_time_s"] == {"value": 61.0, "status": "slicer_estimate"}
    assert report["estimates"]["layer_count"]["value"] == 10.0
    assert report["estimates"]["filament_mass_g"] == {"value": None, "status": "unknown"}
    assert report["overrides"]["process"]["sparse_infill_density"]["declared"] == "25%"
    assert report["overrides"]["process"]["sparse_infill_density"]["preset"] is None
    log = (outputs / "slice.log").read_text()
    assert "--clone-objects" not in log and "--rotate" not in log
    requested = op(
        users["owner"],
        "print_slice.request",
        {"preparation_revision_id": orca_frozen["revision_id"], "recipe_id": orca_approved["id"]},
        idempotency_key="slice",
    )
    media = output_media("3mf", spec["adapter"])
    files = {p: (outputs / p).read_bytes() for p in media}
    register_outputs(requested["build_id"], files, media, REPORT_PATH)
    ref = {"preparation_revision_id": orca_frozen["revision_id"], "build_id": requested["build_id"]}
    read = op(users["viewer"], "print_slice.read", ref)
    assert read["report"]["applied_settings"]["printer_settings_id"] == "Qidi Q1 Pro 0.4 nozzle"
    assert read["printable"] == "not_evaluated" and read["physical_qualification"] is False


