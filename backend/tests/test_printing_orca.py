def test_synthetic_slicer_fixtures_are_closed_meshes_of_known_volume():
    import runpy
    from collections import Counter
    from pathlib import Path

    gen = runpy.run_path(str(Path(__file__).parents[2] / "toolpacks/slicer/generate_fixture.py"))
    for facets, volume in ((gen["box"](0, 0, 0, 20, 20, 20), 8000.0), (gen["tee"](), 1900.0)):
        edges = Counter((f[i], f[(i + 1) % 3]) for f in facets for i in range(3))
        assert all(n == 1 and edges[(b, a)] == 1 for (a, b), n in edges.items())
        assert gen["volume"](facets) == pytest.approx(volume)
    assert gen["malformed"]()[80:84] == (1000).to_bytes(4, "little")
