def test_orca_adapter_rejects_unparseable_models_and_changed_bytes(orca_approved, tmp_path):
    spec = json.loads(orca_approved["argv"][-1])
    (tmp_path / "a").mkdir()
    done, outputs = run_orca(tmp_path / "a", spec, MODEL + b"tampered")
    assert done.returncode != 0 and not (outputs / "slice.json").exists()
