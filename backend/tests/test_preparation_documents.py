def configuration(root, **changes):
    return {
        "root_revision_id": root["revision_id"],
        "standalone_decision": "make",
        "standalone_basis": "Original synthetic workshop decision",
        **changes,
    }


def retain(user, config, key="documents"):
    reviewed = op(user, "preparation_documents.review", config)
    saved = op(
        user,
        "preparation_documents.generate",
        config,
        expected_state=reviewed["state"],
        idempotency_key=key,
    )
    return reviewed, saved


def files(user, saved):
    output = {}
    for filename in DOCUMENTS:
        result = op(
            user,
            "preparation_documents.download",
            {"document_set_id": saved["document_set_id"], "filename": filename},
        )
        data = base64.b64decode(result["data_base64"], validate=True)
        assert hashlib.sha256(data).hexdigest() == result["sha256"]
        assert len(data) == result["size"]
        assert result["inputs_sha256"] == saved["sha256"]
        output[filename] = data
    return output


