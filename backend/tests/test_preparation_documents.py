def test_stale_review_replay_history_database_immutability_and_registered_http(users, project):
    user = users["owner"]
    _, root = cable(user, project)
    config = configuration(root)
    review, saved = retain(user, config)
    original = files(user, saved)
    assert (
        op(
            user,
            "preparation_documents.generate",
            config,
            expected_state=review["state"],
            idempotency_key="documents",
        )
        == saved
    )
    with pytest.raises(Conflict):
        op(
            user,
            "preparation_documents.generate",
            {**config, "quantity": 2},
            expected_state=review["state"],
            idempotency_key="stale",
        )
    with pytest.raises(IdempotencyMismatch):
        op(
            user,
            "preparation_documents.generate",
            {**config, "quantity": 2},
            expected_state=review["state"],
            idempotency_key="documents",
        )
    _, newer = retain(user, {**config, "quantity": 2}, "documents-new")
    assert newer["sha256"] != saved["sha256"]
    assert files(user, saved) == original
    record = DocumentSet.objects.get(id=saved["document_set_id"])
    with pytest.raises(DatabaseError), transaction.atomic():
        DocumentSet.objects.filter(pk=record.pk).update(generator="different")
    with pytest.raises(DatabaseError), transaction.atomic():
        DocumentOutput.objects.filter(document_set=record).delete()
    client = api(users["viewer"])
    response = post_op(client, "preparation_documents.read", {"document_set_id": str(record.id)})
    assert response.status_code == 200 and response.json()["result"] == saved
    assert (
        post_op(
            client,
            "preparation_documents.generate",
            config,
            expected_state=review["state"],
            idempotency_key="viewer",
        ).status_code
        == 403
    )
    assert (
        post_op(
            api(users["outsider"]),
            "preparation_documents.read",
            {"document_set_id": str(record.id)},
        ).status_code
        == 404
    )


