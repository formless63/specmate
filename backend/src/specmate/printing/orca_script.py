"""Trusted OrcaSlicer adapter text; executed only by an approved isolated native runner.

The program checks the exact model bytes and the pinned OrcaSlicer release, resolves the
named bundled vendor presets (machine, process, filament) by flattening their
``inherits`` chains inside the image, applies only the declared overrides, runs the
OrcaSlicer command line with fixed arguments and reports output hashes and the slice
facts OrcaSlicer itself writes into the G-code. A fact the slicer does not state, or
states as zero, is reported unknown. Nothing is sent to a printer.
"""

import inspect
import re

ADAPTER = "print-slice-orcaslicer-v1"
SETTINGS = (
    "printer_settings_id",
    "print_settings_id",
    "filament_settings_id",
    "printer_model",
    "layer_height",
    "nozzle_diameter",
    "filament_density",
    "filament_diameter",
    "printable_area",
    "enable_support",
    "support_on_build_plate_only",
    "gcode_flavor",
)


def gcode_facts(text: str) -> dict:
    """Facts OrcaSlicer states in its own G-code; unstated or zero values stay unknown.

    Two header dialects exist: generic printer presets state "total layers count" and a
    normal-mode estimate; Bambu Lab machine presets state "total layer number" and a
    model/total time line. Runs inside the tool image and in application tests alike.
    """

    def field(pattern):
        match = re.search(pattern, text, re.M)
        return match.group(1).strip() if match else None

    def known(value):
        if value is None or value <= 0:
            return {"value": None, "status": "unknown"}
        return {"value": value, "status": "slicer_estimate"}

    def duration(value):
        if value is None:
            return None
        units = {"d": 86400, "h": 3600, "m": 60, "s": 1}
        parts = re.findall(r"(\d+)\s*([dhms])", value)
        return float(sum(int(n) * units[u] for n, u in parts)) if parts else None

    def number(value):
        try:
            return float(value) if value is not None else None
        except ValueError:
            return None

    layers = field(r"^; total layers count = (\d+)$") or field(r"^; total layer number: (\d+)$")
    total = field(r"^; estimated printing time \(normal mode\) = (.+)$") or field(
        r"^; model printing time: [^;]*; total estimated time: (.+)$"
    )
    facts = {
        "print_time_s": known(duration(total)),
        "model_print_time_s": known(duration(field(r"^; model printing time: ([^;]+);"))),
        "filament_length_mm": known(number(field(r"^; filament used \[mm\] = ([0-9.]+)"))),
        "filament_volume_cm3": known(number(field(r"^; filament used \[cm3\] = ([0-9.]+)"))),
        "filament_mass_g": known(number(field(r"^; (?:total )?filament used \[g\] = ([0-9.]+)"))),
        "layer_count": known(number(layers)),
    }
    applied = {}
    for key in SETTINGS:
        value = field(r"^; " + key + r" = (.*)$")
        applied[key] = value.strip('"') if value is not None else None
    return {
        "producer": field(r"^; generated by (OrcaSlicer [0-9.]+)"),
        "facts": facts,
        "applied_settings": applied,
    }


_MAIN = r"""
import hashlib, json, os, pathlib, re, shutil, subprocess, sys

SETTINGS = {settings!r}

{facts}

raw_spec = sys.argv[1]
spec = json.loads(raw_spec)
assert spec["adapter"] == "print-slice-orcaslicer-v1"
out = pathlib.Path("/outputs")
model = pathlib.Path("/inputs") / spec["part"]["path"]
assert model.is_file() and not model.is_symlink()
ROOT = pathlib.Path("/opt/orcaslicer")
PROFILES = ROOT / "resources" / "profiles"
log_lines = []


def note(message):
    log_lines.append(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def fail(message):
    (out / "slice.log").write_text("\n".join(log_lines + ["error: " + message]) + "\n")
    print(message, file=sys.stderr)
    raise SystemExit(2)


before = digest(model)
if before != spec["part"]["sha256"]:
    fail("Model bytes differ from the exact pin")
tool = spec["tool"]
release = pathlib.Path("/opt/specmate/orcaslicer-release.txt").read_text().split("\n")
pinned = [tool["name"] + " " + tool["package_version"], tool["package"], tool["release_sha256"]]
if release[:3] != pinned:
    fail("Installed OrcaSlicer release differs from the pin")

KINDS = {"printer": "machine", "process": "process", "material": "filament"}


def index(vendor, kind):
    found = {}
    base = PROFILES / vendor / kind
    if not base.is_dir():
        return found
    for path in sorted(base.rglob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError):
            continue
        if isinstance(data, dict) and isinstance(data.get("name"), str):
            found.setdefault(data["name"], data)
    return found


def resolve(role, preset):
    vendor, kind = preset["vendor"], KINDS[role]
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 ._-]{0,63}", vendor):
        fail("Unsafe vendor name")
    meta = PROFILES / (vendor + ".json")
    if not meta.is_file():
        fail("Vendor bundle " + vendor + " is not in this OrcaSlicer release")
    version = json.loads(meta.read_text(encoding="utf-8")).get("version")
    if version != preset["bundle_version"]:
        fail("Vendor bundle " + vendor + " version " + str(version) + " differs from the pin")
    names = index(vendor, kind)
    fallback = index("OrcaFilamentLibrary", kind) if kind == "filament" else {}
    leaf = names.get(preset["name"])
    if leaf is None:
        fail(role + " preset " + preset["name"] + " is not in vendor bundle " + vendor)
    if str(leaf.get("instantiation", "")).lower() != "true":
        fail(role + " preset " + preset["name"] + " is a base preset, not a selectable one")
    chain, current, seen = [], leaf, set()
    while True:
        chain.append(current)
        parent = current.get("inherits") or ""
        if not parent:
            break
        if parent in seen or len(chain) > 32:
            fail("Preset inheritance loops for " + preset["name"])
        seen.add(parent)
        current = names.get(parent) or fallback.get(parent)
        if current is None:
            fail("Parent preset " + parent + " of " + preset["name"] + " is missing")
    merged = {}
    for item in reversed(chain):
        merged.update(item)
    merged["inherits"] = ""
    merged["name"] = preset["name"]
    note(role + " preset " + vendor + "/" + kind + "/" + preset["name"] + " chain: "
         + " <- ".join(c.get("name", "?") for c in chain))
    return merged


work = pathlib.Path("/tmp/specmate-orca")
settings_dir = work / "settings"
result_dir = work / "out"
data_dir = work / "data"
for path in (settings_dir, result_dir, data_dir):
    path.mkdir(parents=True, exist_ok=True)
files = {}
effective_overrides = {}
for role, preset in sorted(spec["presets"].items()):
    merged = resolve(role, preset)
    overrides = spec["overrides"].get(role, {})
    effective_overrides[role] = {
        k: {"preset": merged.get(k), "declared": v} for k, v in sorted(overrides.items())
    }
    merged.update(overrides)
    target = settings_dir / (KINDS[role] + ".json")
    target.write_text(json.dumps(merged, sort_keys=True, indent=1))
    files[role] = target

fmt = spec["output_format"]
argv = [
    str(ROOT / "AppRun"),
    "--datadir", str(data_dir),
    "--slice", "0",
    "--load-settings", str(files["printer"]) + ";" + str(files["process"]),
    "--load-filaments", str(files["material"]),
    "--outputdir", str(result_dir),
]
if fmt == "3mf":
    argv += ["--export-3mf", "sliced.3mf"]
# OrcaSlicer 2.4.2 terminates with SIGSEGV on --rotate/--rotate-x/--rotate-y, so only
# as-modeled orientation is accepted; the application refuses rotations earlier.
if spec["orientation"]["status"] != "as_modelled":
    fail("Only as-modeled orientation is supported with OrcaSlicer 2.4.2")
if spec["copies"] > 1:
    argv += ["--clone-objects", str(spec["copies"]), "--arrange", "1"]
argv += ["--ensure-on-bed", str(model)]
env = {
    "PATH": "/usr/bin:/bin", "HOME": str(data_dir), "TMPDIR": "/tmp", "LC_ALL": "C",
    "XDG_RUNTIME_DIR": str(work),
}
note(json.dumps(argv))
proc = subprocess.run(argv, capture_output=True, env=env, cwd=str(work), timeout=840)
note((proc.stdout + proc.stderr).decode("utf-8", "replace").strip())
result_file = result_dir / "result.json"
result = {}
if result_file.is_file():
    try:
        result = json.loads(result_file.read_text())
    except ValueError:
        result = {}
note("result.json: " + json.dumps(result, sort_keys=True))
for name in sorted(os.listdir(result_dir)):
    if name.endswith(".log"):
        note(name + ": " + (result_dir / name).read_text(errors="replace").strip())
if proc.returncode or result.get("return_code") != 0:
    fail("OrcaSlicer failed (exit " + str(proc.returncode) + ", return_code "
         + str(result.get("return_code")) + "): " + str(result.get("error_string")))
if digest(model) != before:
    fail("Model bytes changed during slicing")
gcode = result_dir / "plate_1.gcode"
if not gcode.is_file():
    fail("OrcaSlicer reported success without plate G-code")
shutil.copyfile(gcode, out / "slice.gcode")
if fmt == "3mf":
    shutil.copyfile(result_dir / "sliced.3mf", out / "sliced.3mf")
data = (out / "slice.gcode").read_bytes()
parsed = gcode_facts(data.decode("utf-8", "replace"))
body = re.sub(rb"^; generated by [^\n]*\n", b"", data, count=1, flags=re.M)
outputs = []
(out / "slice.log").write_text("\n".join(log_lines) + "\n")
for path in sorted(["slice.log", "slice.gcode"] + (["sliced.3mf"] if fmt == "3mf" else [])):
    content = (out / path).read_bytes()
    sha = hashlib.sha256(content).hexdigest()
    outputs.append({"path": path, "sha256": sha, "size": len(content)})
report = {
    "format_version": 1,
    "adapter": "print-slice-orcaslicer-v1",
    "input_sha256": hashlib.sha256(raw_spec.encode()).hexdigest(),
    "tool": {k: tool[k] for k in ("name", "package", "package_version", "release_sha256")},
    "producer": parsed["producer"],
    "model_sha256": before,
    "source_unchanged": True,
    "slicer_exit_code": 0,
    "outputs": outputs,
    "estimates": parsed["facts"],
    "applied_settings": parsed["applied_settings"],
    "overrides": effective_overrides,
    "gcode_body_sha256": hashlib.sha256(body).hexdigest(),
    "printable": "not_evaluated",
    "printer_submission": "not_performed",
    "physical_qualification": False,
}
(out / "slice.json").write_text(json.dumps(report, sort_keys=True, separators=(",", ":")))
"""

SCRIPT = _MAIN.replace("{settings!r}", repr(SETTINGS)).replace(
    "{facts}", inspect.getsource(gcode_facts)
)
