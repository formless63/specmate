"""Host-only regression checks; these do not claim native tool qualification."""

import contextlib
import copy
import importlib.util
import io
import json
import signal
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location(
    "fixture_harness", ROOT / "scripts/check_native_fixtures.py"
)
harness = importlib.util.module_from_spec(spec)
spec.loader.exec_module(harness)


class SemanticOracleTests(unittest.TestCase):
    def setUp(self):
        self.expected = json.loads((ROOT / harness.EXPECTATIONS).read_text())
        # Explicit observed-style sample, never generated by the extractor or generator.
        self.facts = {
            "units": "mm",
            "outline": [[0, 0], [40, 0], [40, 25], [0, 25]],
            "mounting_holes": [[3, 3], [37, 3], [3, 22], [37, 22]],
            "terminals": ["J1.1", "J1.2", "R1.1", "R1.2"],
            "copper_nets": {"N1": ["J1.1", "R1.1"], "N2": ["J1.2", "R1.2"]},
            "component_passages": [
                {
                    "kind": "resistor",
                    "from": "R1.1",
                    "to": "R1.2",
                    "resistance_ohm": 1000,
                }
            ],
        }

    def test_order_and_outline_winding_do_not_change_meaning(self):
        self.facts["outline"] = [[40, 25], [40, 0], [0, 0], [0, 25], [40, 25]]
        self.facts["mounting_holes"].reverse()
        self.facts["terminals"].reverse()
        self.facts["copper_nets"]["N1"].reverse()
        harness.compare_facts(self.facts, self.expected)

    def test_resistor_must_not_merge_copper_nets(self):
        self.facts["copper_nets"] = {"N1": ["J1.1", "J1.2", "R1.1", "R1.2"]}
        with self.assertRaisesRegex(ValueError, "Copper nets differ"):
            harness.compare_facts(self.facts, self.expected)

    def test_connectivity_alone_cannot_prove_resistor_value(self):
        self.facts["component_passages"][0]["resistance_ohm"] = 0
        with self.assertRaisesRegex(ValueError, "Resistor semantics differ"):
            harness.compare_facts(self.facts, self.expected)

    def test_duplicate_terminal_is_not_hidden_by_set_comparison(self):
        self.facts["terminals"].append("R1.1")
        with self.assertRaisesRegex(ValueError, "Terminals differ"):
            harness.compare_facts(self.facts, self.expected)

    def test_geometric_errors_are_not_hidden_by_matching_bounds_or_count(self):
        for key, index in (("outline", 2), ("mounting_holes", 0)):
            with self.subTest(key=key):
                altered = copy.deepcopy(self.facts)
                altered[key][index][0] -= 0.1
                with self.assertRaises(ValueError):
                    harness.compare_facts(altered, self.expected)


class HarnessAdmissionTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.destination = Path(self.temp.name) / "evidence"

    def invoke(self, *args):
        with (
            contextlib.redirect_stdout(io.StringIO()),
            contextlib.redirect_stderr(io.StringIO()),
        ):
            return harness.main(list(args))

    def test_static_checks_never_start_a_container(self):
        with patch.object(
            harness, "Docker", side_effect=AssertionError("unexpected native execution")
        ):
            self.assertEqual(self.invoke(), 0)

    def test_existing_evidence_is_not_overwritten_on_rejection(self):
        self.destination.mkdir()
        sentinel = self.destination / "evidence.json"
        sentinel.write_text("preserve this result")
        self.assertEqual(
            self.invoke("--real-tools", "--output", str(self.destination)), 1
        )
        self.assertEqual(sentinel.read_text(), "preserve this result")

    def test_unavailable_image_is_a_nonpassing_result(self):
        with patch.object(harness, "Docker") as docker:
            docker.return_value.command.side_effect = harness.ToolUnavailable(
                "not cached"
            )
            self.assertEqual(
                self.invoke("--real-tools", "--output", str(self.destination)), 2
            )
        evidence = json.loads((self.destination / "evidence.json").read_text())
        self.assertEqual(evidence["status"], "unavailable")

    def test_zero_or_excessive_timeout_is_rejected_before_native_execution(self):
        with patch.object(
            harness, "Docker", side_effect=AssertionError("unexpected native execution")
        ):
            for value in ("0", "999999"):
                with self.subTest(timeout=value):
                    self.assertEqual(
                        self.invoke(
                            "--real-tools",
                            "--output",
                            str(self.destination),
                            "--timeout-seconds",
                            value,
                        ),
                        1,
                    )
        self.assertFalse(self.destination.exists())

    def test_source_hash_tampering_is_detected_without_native_execution(self):
        with patch.object(harness, "hash_file", return_value="0" * 64):
            self.assertEqual(self.invoke(), 1)

    def test_metadata_and_unused_svg_definitions_are_not_an_export(self):
        svg = Path(self.temp.name) / "board.svg"
        for content in (
            "<metadata>nothing drawn</metadata>",
            '<defs><path d="M0 0 L40 25"/></defs>',
        ):
            with self.subTest(content=content):
                svg.write_text(
                    f'<svg xmlns="http://www.w3.org/2000/svg">{content}</svg>'
                )
                with self.assertRaisesRegex(ValueError, "no drawable geometry"):
                    harness.validate_svg(svg)

    def test_checkpoint_deadline_runs_cleanup_and_stops_remaining_cases(self):
        self.destination.mkdir()
        cleaned = []

        class InterruptedCase(unittest.TestCase):
            def runTest(self):
                self.addCleanup(lambda: cleaned.append(True))
                signal.raise_signal(signal.SIGALRM)

        suite = unittest.TestSuite(InterruptedCase() for _ in range(6))
        original_handler = signal.getsignal(signal.SIGALRM)
        with (
            patch.object(
                harness.unittest.defaultTestLoader,
                "loadTestsFromTestCase",
                return_value=suite,
            ),
            self.assertRaisesRegex(ValueError, "interrupted"),
        ):
            harness.runner_checkpoint("unused-unit-test-image", self.destination)
        self.assertEqual(cleaned, [True])
        self.assertEqual(signal.getsignal(signal.SIGALRM), original_handler)


if __name__ == "__main__":
    unittest.main()
